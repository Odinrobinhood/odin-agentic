import { readFileSync } from 'node:fs';
import { createPublicClient, fallback, getAddress, http, parseAbi, type Address } from 'viem';
import { MULTICALL3 } from './catalog.ts';

/** Reference (oracle) prices in USDG per token; tokens without a fresh feed are absent. */
export type OraclePrices = (tokens: Address[]) => Promise<Map<Address, number>>;

type Feed = { token: Address; feed: Address; maxAgeSeconds: number };
const feedAbi = parseAbi(['function latestRoundData() view returns (uint80, int256, uint256, uint256, uint80)']);

/** Feeds from the verified map (deploy/chainlink.mainnet.json, generated by packages/risk/scripts/chainlink-feeds.ts). */
export function loadFeedMap(file: string): Feed[] {
  const raw = JSON.parse(readFileSync(file, 'utf8')) as { feeds?: { token: string; feed: string; maxAgeSeconds: number }[] };
  if (!Array.isArray(raw.feeds)) throw new Error(`${file}: "feeds" must be an array`);
  return raw.feeds.map((f) => ({ token: getAddress(f.token), feed: getAddress(f.feed), maxAgeSeconds: Number(f.maxAgeSeconds) }));
}

/**
 * Chainlink reference prices for the minute snapshots (architecture §3.6): one Multicall3 batch per minute.
 * Feeds are USD with 8 decimals and Robinhood Stock Token feeds already include the token multiplier; USDG is
 * the unit of account (1 USD, as in the Risk Engine). Stale, non-positive or failed reads give no price.
 */
export function chainlinkOracle(rpcUrls: string[], feeds: Feed[], now: () => Date = () => new Date()): OraclePrices {
  const c = createPublicClient({ transport: fallback(rpcUrls.map((u) => http(u, { timeout: 10_000, retryCount: 1 })), { rank: false }) });
  return async (tokens) => {
    const want = new Set(tokens);
    const fs = feeds.filter((f) => want.has(f.token));
    const out = new Map<Address, number>();
    if (!fs.length) return out;
    const r = await c.multicall({
      multicallAddress: MULTICALL3,
      allowFailure: true,
      contracts: fs.map((f) => ({ address: f.feed, abi: feedAbi, functionName: 'latestRoundData' as const })),
    });
    const t = Math.floor(now().getTime() / 1000);
    fs.forEach((f, i) => {
      const x = r[i];
      if (x?.status !== 'success') return;
      const [, answer, , updatedAt] = x.result;
      if (answer <= 0n || t - Number(updatedAt) > f.maxAgeSeconds) return;
      out.set(f.token, Number(answer) / 1e8);
    });
    return out;
  };
}
